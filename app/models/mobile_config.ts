import vine from "@vinejs/vine";
import { DateTime } from "luxon";

import { BaseModel } from "@adonisjs/lucid/orm";
import db from "@adonisjs/lucid/services/db";

import { typedColumn } from "#decorators/typed_model";
import CacheState from "#models/cache_state";
import { preloadRelations } from "#scopes/preload_helper";
import { handleSearchQuery } from "#scopes/search_helper";
import { handleSortQuery } from "#scopes/sort_helper";

export default class MobileConfig extends BaseModel {
  @typedColumn({ isPrimary: true, type: "integer" })
  declare id: number;

  @typedColumn({ type: "integer", autoGenerated: true })
  declare cmsReferenceNumber: number;

  @typedColumn({ type: "integer", autoGenerated: true })
  declare translatorReferenceNumber: number;

  @typedColumn({
    type: "integer",
    validator: vine.number().withoutDecimals().min(1),
  })
  declare daySwapLookahead: number;

  @typedColumn({
    type: "string",
    validator: vine
      .string()
      .url({ protocols: ["https"], require_protocol: true }),
  })
  declare sksMicroserviceUrl: string;

  @typedColumn({
    type: "string",
    validator: vine
      .string()
      .url({ protocols: ["https"], require_protocol: true }),
  })
  declare parkingMicroserviceUrl: string;

  @typedColumn({
    type: "string",
    validator: vine
      .string()
      .url({ protocols: ["https"], require_protocol: true })
      .optional(),
  })
  declare boothsApiBaseUrl: string | null;

  @typedColumn({ type: "boolean", hasDefault: true })
  declare boothsEnabled: boolean;

  @typedColumn({ type: "boolean", hasDefault: true })
  declare killswitchOfDoomAndDespair: boolean;

  @typedColumn.dateTime({ autoCreate: true })
  declare createdAt: DateTime;

  @typedColumn.dateTime({ autoCreate: true, autoUpdate: true })
  declare updatedAt: DateTime;

  public static async bumpCmsCache() {
    await db.transaction(async (trx) => {
      await MobileConfig.query({ client: trx }).increment(
        "cms_reference_number",
        1,
      );
      await CacheState.touchGlobalLastModified(trx);
    });
  }

  public static async bumpTranslatorCache() {
    await db.transaction(async (trx) => {
      await MobileConfig.query({ client: trx }).increment(
        "translator_reference_number",
        1,
      );
      await CacheState.touchGlobalLastModified(trx);
    });
  }

  static readonly preloadRelations = preloadRelations();
  static readonly handleSearchQuery = handleSearchQuery();
  static readonly handleSortQuery = handleSortQuery();
}
